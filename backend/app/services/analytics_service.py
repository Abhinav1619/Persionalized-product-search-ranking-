def overview(db: Session) -> dict[str, Any]:
    product_count = db.query(func.count(Product.id)).scalar() or 0
    events = db.query(InteractionEvent).all()

    counts = Counter(e.event_type for e in events)
    impressions = counts.get("impression", 0) + counts.get("search", 0)
    clicks = counts.get("click", 0)
    atc = counts.get("atc", 0)
    purchases = counts.get("purchase", 0)
    searches = counts.get("search", 0)

    # Activity over last 7 days
    now = datetime.utcnow()
    days = [(now - timedelta(days=i)).strftime("%Y-%m-%d") for i in range(6, -1, -1)]
    activity = {d: {"search": 0, "click": 0, "atc": 0, "purchase": 0} for d in days}
    for e in events:
        day = e.created_at.strftime("%Y-%m-%d")
        if day in activity and e.event_type in activity[day]:
            activity[day][e.event_type] += 1

    # Category engagement via product joins
    product_cats = {p.id: p.category for p in db.query(Product).all()}
    cat_counter: dict[str, int] = defaultdict(int)
    for e in events:
        if e.product_id and e.product_id in product_cats and e.event_type in {"click", "atc", "purchase"}:
            cat_counter[product_cats[e.product_id]] += 1

    return {
        "total_products": product_count,
        "search_requests": searches,
        "impressions": impressions,
        "clicks": clicks,
        "add_to_cart": atc,
        "purchases": purchases,
        "ctr": metric_payload(
            click_through_rate(max(impressions, searches), clicks),
            "clicks / (impressions + searches) from demo events",
        ),
        "atc_rate": metric_payload(atc_rate(clicks, atc), "add-to-cart / clicks from demo events"),
        "purchase_conversion": metric_payload(
            purchase_conversion(atc, purchases),
            "purchases / add-to-cart from demo events",
        ),
        "activity_over_time": [{"date": d, **activity[d]} for d in days],
        "funnel": [
            {"stage": "Search", "count": searches},
            {"stage": "Click", "count": clicks},
            {"stage": "Add to Cart", "count": atc},
            {"stage": "Purchase", "count": purchases},
        ],
        "category_engagement": [
            {"category": k, "interactions": v} for k, v in sorted(cat_counter.items(), key=lambda x: -x[1])
        ],
        "events_are_demo": True,
        "disclaimer": "All interaction metrics come from simulated demo events in this application, not production traffic.",
    }


